/**
 * Turns contract/openapi.json into the C# API client for the Windows app (docs/SPEC.md §4.1).
 * It only understands the parts of OpenAPI that our contract uses, and it throws on anything else,
 * so a new kind of schema is noticed when `pnpm contract` runs, not on a PC.
 *
 * Only the kid-device routes are generated: paths that start with `/v1/device/`, plus `/v1/enrol`.
 * The shape mirrors kotlin-gen.ts: the same Schema/OpenApiDoc types, the same pascal() helper,
 * the same "declare a placeholder, then fill it" trick so a record comes before its inline types.
 */

import type { OpenApiDoc, Operation, Schema } from './kotlin-gen.js';

export const HEADER = '// Generated by server/scripts/csharp-client.ts from contract/openapi.json. Do not edit: run `pnpm contract`.';

/** `parent-mode` → `ParentMode`, `endedBy` → `EndedBy`. */
function pascal(text: string) {
  return text
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((part) => part[0]!.toUpperCase() + part.slice(1))
    .join('');
}

function types(schema: Schema) {
  return Array.isArray(schema.type) ? schema.type : schema.type ? [schema.type] : [];
}

function refName(ref: string) {
  return ref.replace('#/components/schemas/', '');
}

/** A number choice is an `anyOf` of number enums and maybe `null`, like `ParentModeDuration`. */
function isNumberEnum(schema: Schema) {
  return !!schema.anyOf?.every((s) => s.type === 'null' || (s.type === 'number' && s.enum?.every((v) => Number.isInteger(v))));
}

/** Escape `&`, `<` and `>` for an XML doc comment. */
function docEscape(text: string) {
  return text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

export function generateCSharp(doc: OpenApiDoc): { models: string; client: string } {
  const schemas = doc.components.schemas;
  const out: string[] = [];
  const declared = new Set<string>();

  /** Records a C# type name. An inline type may not take the name of a schema. */
  function declare(typeName: string, inline: boolean) {
    if (declared.has(typeName) || (inline && schemas[typeName])) {
      throw new Error(`two C# types are named ${typeName}`);
    }
    declared.add(typeName);
  }

  /** Whether a value of this schema can be null. */
  function nullable(schema: Schema): boolean {
    if (schema.$ref) {
      return nullable(schemas[refName(schema.$ref)]!);
    }
    if (schema.anyOf) {
      return schema.anyOf.some((s) => s.type === 'null');
    }
    return types(schema).includes('null') || !!schema.enum?.includes(null);
  }

  /** The C# type of a schema, without the `?`. Inline objects and enums are declared as `owner`. */
  function csharpType(schema: Schema, owner: string): string {
    if (schema.$ref) {
      const target = refName(schema.$ref);
      const s = schemas[target]!;
      // Plain strings and number choices have no C# type of their own.
      if (!s.enum && !s.anyOf && !s.properties && types(s).includes('string')) return 'string';
      if (isNumberEnum(s)) return 'int';
      return target;
    }
    if (isNumberEnum(schema)) return 'int';
    if (schema.anyOf) throw new Error(`${owner}: anyOf is only supported for number choices`);
    const t = types(schema).filter((x) => x !== 'null');
    if (t.length !== 1) throw new Error(`${owner}: unsupported type ${JSON.stringify(schema.type)}`);
    switch (t[0]) {
      case 'string':
        if (schema.enum) {
          declareEnum(owner, schema, true);
          return owner;
        }
        return 'string';
      case 'integer':
        return 'int';
      case 'number':
        return 'double';
      case 'boolean':
        return 'bool';
      case 'array': {
        const itemType = csharpType(schema.items!, `${owner}Item`);
        const suffix = schema.items && nullable(schema.items) ? '?' : '';
        return `IReadOnlyList<${itemType}${suffix}>`;
      }
      case 'object':
        if (!schema.properties) {
          if (schema.additionalProperties !== undefined) return 'JsonElement';
          throw new Error(`${owner}: an object needs properties or additionalProperties`);
        }
        declareRecord(owner, schema, true);
        return owner;
      default:
        throw new Error(`${owner}: unsupported type ${t[0]}`);
    }
  }

  function declareEnum(typeName: string, schema: Schema, inline: boolean) {
    declare(typeName, inline);
    const values = schema.enum!.filter((v): v is string => v !== null);
    const lines = values.map((v) => {
      const member = pascal(v);
      if (/^[0-9]/.test(member)) throw new Error(`${typeName}: unsupported enum value ${v}`);
      return `    [JsonStringEnumMemberName(${JSON.stringify(v)})] ${member},`;
    });
    out.push(
      `[JsonConverter(typeof(JsonStringEnumConverter<${typeName}>))]\npublic enum ${typeName}\n{\n${lines.join('\n')}\n}`,
    );
  }

  function declareRecord(typeName: string, schema: Schema, inline: boolean) {
    declare(typeName, inline);
    const index = out.push('') - 1;
    const required = new Set(schema.required ?? []);
    const propNames = Object.keys(schema.properties!);
    const lines = propNames.map((prop) => {
      const s = schema.properties![prop];
      const t = csharpType(s, typeName + pascal(prop));
      const isNull = nullable(s);
      const isRequired = required.has(prop);
      const attr = isRequired
        ? `[property: JsonPropertyName(${JSON.stringify(prop)})]`
        : `[property: JsonPropertyName(${JSON.stringify(prop)}), JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]`;
      const type = isRequired ? `${t}${isNull ? '?' : ''}` : `${t}?`;
      const defaultSuffix = isRequired ? '' : ' = null';
      return `    ${attr} ${type} ${pascal(prop)}${defaultSuffix}`;
    });
    // Required properties first, in contract order, then the optional ones in contract order.
    const ordered = [...lines.filter((_, i) => required.has(propNames[i])), ...lines.filter((_, i) => !required.has(propNames[i]))];
    out[index] = `public sealed record ${typeName}(\n${ordered.map((l, i) => `${i === ordered.length - 1 ? l + ');' : l + ','}`).join('\n')}`;
  }

  // Which schemas the device routes use: follow every $ref until nothing new is found.
  const used = new Set<string>();
  const queue: string[] = [];
  const collect = (schema?: Schema) => {
    if (!schema) return;
    const walk = (s?: Schema) => {
      if (!s || typeof s !== 'object') return;
      if (s.$ref) {
        const name = refName(s.$ref);
        if (!used.has(name)) {
          used.add(name);
          queue.push(name);
        }
        return;
      }
      for (const v of Object.values(s.properties ?? {})) walk(v as Schema);
      walk(s.items);
      for (const v of s.anyOf ?? []) walk(v);
      if (typeof s.additionalProperties === 'object') walk(s.additionalProperties);
    };
    walk(schema);
  };

  const deviceOps: { path: string; method: string; op: Operation }[] = [];
  for (const [path, methods] of Object.entries(doc.paths)) {
    if (path === '/v1/enrol' || path.startsWith('/v1/device/')) {
      for (const [method, op] of Object.entries(methods)) {
        deviceOps.push({ path, method, op });
      }
    }
  }
  for (const { op } of deviceOps) {
    collect(op.requestBody?.content['application/json']?.schema);
    for (const r of Object.values(op.responses)) collect(r.content?.['application/json']?.schema);
  }
  while (queue.length) {
    const name = queue.shift()!;
    collect(schemas[name]);
  }

  // Walk components.schemas in contract order, emitting each used schema.
  for (const [schemaName, schema] of Object.entries(schemas)) {
    if (!used.has(schemaName)) continue;
    if (schema.properties) {
      declareRecord(schemaName, schema, false);
    } else if (schema.enum) {
      declareEnum(schemaName, schema, false);
    } else if (types(schema).includes('string') || isNumberEnum(schema)) {
      // Plain strings and number choices have no type of their own.
    } else {
      throw new Error(`${schemaName}: unsupported schema`);
    }
  }

  const context = [
    '/// <summary>The System.Text.Json source generator for every type above. A missing required field, or a null where none is allowed, throws.</summary>',
    '[JsonSourceGenerationOptions(RespectNullableAnnotations = true, RespectRequiredConstructorParameters = true)]',
    ...[...declared].map((n) => `[JsonSerializable(typeof(${n}))]`),
    'public partial class ApiJsonContext : JsonSerializerContext',
    '{',
    '}',
  ].join('\n');

  const models = [
    HEADER,
    '#nullable enable',
    'using System.Text.Json;\nusing System.Text.Json.Serialization;',
    'namespace ScreenTime.Core.Api;',
    ...out,
    context,
  ].join('\n\n');

  // The client: one method per device operation, in the order of the contract.
  const methods: string[] = [];
  const seen = new Set<string>();
  for (const { path, method, op } of deviceOps) {
    const segments = path.replace(/^\/v1(\/|$)/, '/').split('/').filter(Boolean);
    const fixed = segments.filter((s) => !s.startsWith('{'));
    const endsWithParam = segments.at(-1)?.startsWith('{') ?? false;
    const fn = pascal(`${method} ${fixed.join(' ')}${endsWithParam ? ' by id' : ''}`);
    if (seen.has(fn)) throw new Error(`two operations are named ${fn}`);
    seen.add(fn);

    const params: string[] = [];
    const pathParams = (op.parameters ?? []).filter((p) => p.in === 'path');
    for (const p of op.parameters ?? []) {
      if (p.in !== 'path' && p.in !== 'query') throw new Error(`${method} ${path}: unsupported parameter in ${p.in}`);
    }
    for (const p of pathParams) params.push(`string ${p.name}`);
    const bodySchema = op.requestBody?.content['application/json']?.schema;
    const bodyType = bodySchema ? csharpType(bodySchema, `${fn}Body`) : null;
    if (bodyType) params.push(`${bodyType} body`);
    const conditional = '304' in op.responses;
    if (conditional) params.push('string? ifNoneMatch = null');
    params.push('CancellationToken cancellationToken = default');

    const success = Object.entries(op.responses).find(([code, r]) => code.startsWith('2') && r.content?.['application/json']);
    const resultSchema = success?.[1].content!['application/json']!.schema;
    const resultType = resultSchema ? csharpType(resultSchema, `${fn}Result`) : null;
    const returns = conditional ? `Conditional<${resultType}>` : resultType ? resultType : 'Task';

    const csharpPath = path.replace(/^\//, '').replace(/\{([^}]+)\}/g, (_, p: string) => `{Uri.EscapeDataString(${p})}`);
    const pathArg = pathParams.length ? `$"${csharpPath}"` : `"${csharpPath}"`;
    const auth = op.security?.length ? 'true' : 'false';

    let bodyLine: string;
    if (conditional) {
      bodyLine = `GetConditionalAsync(${pathArg}, auth: ${auth}, ifNoneMatch, ApiJsonContext.Default.${resultType}, cancellationToken);`;
    } else if (bodyType && resultType) {
      bodyLine = `SendAsync(HttpMethod.${pascal(method)}, ${pathArg}, auth: ${auth}, body, ApiJsonContext.Default.${bodyType}, ApiJsonContext.Default.${resultType}, cancellationToken);`;
    } else if (resultType) {
      bodyLine = `SendAsync(HttpMethod.${pascal(method)}, ${pathArg}, auth: ${auth}, ApiJsonContext.Default.${resultType}, cancellationToken);`;
    } else if (bodyType) {
      bodyLine = `SendAsync(HttpMethod.${pascal(method)}, ${pathArg}, auth: ${auth}, body, ApiJsonContext.Default.${bodyType}, cancellationToken);`;
    } else {
      bodyLine = `SendAsync(HttpMethod.${pascal(method)}, ${pathArg}, auth: ${auth}, cancellationToken);`;
    }

    const summary = op.summary ?? `${method.toUpperCase()} ${path}`;
    methods.push(
      [
        `    /// <summary>${docEscape(summary)}.</summary>`,
        `    /// <remarks><c>${method.toUpperCase()} ${path}</c></remarks>`,
        `    public ${returns === 'Task' ? 'Task' : `Task<${returns}>`} ${fn}Async(${params.join(', ')}) =>`,
        `        ${bodyLine}`,
      ].join('\n'),
    );
  }

  const client = [
    HEADER,
    '#nullable enable',
    'namespace ScreenTime.Core.Api;',
    [
      '/// <summary>',
      '/// The kid-device routes of the Screen Time API (docs/SPEC.md §9) for the Windows app. Each call throws',
      '/// <see cref="ApiException"/> when the server answers with an error. <c>token</c> gives the device token, or null before enrolment.',
      '/// </summary>',
      'public sealed class ApiClient(HttpClient http, Func<string?> token) : ApiClientBase(http, token)',
      '{',
      methods.join('\n\n'),
      '}',
    ].join('\n'),
  ].join('\n\n');

  return { models: `${models}\n`, client: `${client}\n` };
}
